const routeSelect =
document.getElementById("route");

const stopSelect =
document.getElementById("stop");

const timeSelect =
document.getElementById("time");



function loadStops() {

  const route =
  routes[routeSelect.value];

  stopSelect.innerHTML = "";


  route.stops.forEach((stop,index) => {

    const option =
    document.createElement("option");

    option.value = index;

    option.textContent =
    stop.name;

    stopSelect.appendChild(option);

  });


  calculatePrediction();

}



function getTimeFactor(hour) {

  if (hour >= 7 && hour < 9) {
    return 0.25;
  }

  if (hour >= 17 && hour < 20) {
    return 0.30;
  }

  if (hour >= 12 && hour < 14) {
    return 0.12;
  }

  if (hour >= 21 || hour < 6) {
    return -0.15;
  }

  return 0.03;

}



function calculatePrediction() {

  const routeNumber =
  routeSelect.value;

  const route =
  routes[routeNumber];

  const stopIndex =
  Number(stopSelect.value);

  const stop =
  route.stops[stopIndex];


  const time =
  timeSelect.value;

  const parts =
  time.split(":");

  const hour =
  Number(parts[0]) +
  Number(parts[1]) / 60;


  const timeFactor =
  getTimeFactor(hour);


  const variation =
  Math.sin(
    stopIndex * 1.4 +
    hour
  ) * 0.05;


  let occupancy =
  20 +
  stop.factor * 60 +
  timeFactor * 70 +
  variation * 100;


  occupancy =
  Math.round(occupancy);


  if (occupancy > 96) {
    occupancy = 96;
  }

  if (occupancy < 15) {
    occupancy = 15;
  }


  const passengers =
  Math.round(
    route.capacity *
    occupancy /
    100
  );


  updateInterface(
    occupancy,
    passengers,
    route,
    stop,
    routeNumber,
    hour
  );


  showRouteStops(
    route,
    stopIndex
  );

}



function updateInterface(
  occupancy,
  passengers,
  route,
  stop,
  routeNumber,
  hour
) {

  document.getElementById("percent")
  .textContent =
  occupancy + "%";


  document.getElementById("passengers")
  .textContent =
  passengers;


  document.getElementById("capacity")
  .textContent =
  route.capacity;


  document.getElementById("heroPercent")
  .textContent =
  occupancy + "%";


  document.getElementById("heroRoute")
  .textContent =
  "Bus " + routeNumber;


  const status =
  document.getElementById("status");


  const progress =
  document.getElementById("progressBar");


  let nextBus =
  8;


  if (occupancy < 45) {

    status.textContent =
    "Low";

    status.className =
    "status low";

    progress.style.background =
    "#22c55e";


    document.getElementById("heroStatus")
    .textContent =
    "Low occupancy";


    document.getElementById("recommendation")
    .textContent =
    "Take this bus.";


    document.getElementById("recommendationDetail")
    .textContent =
    "The bus is expected to have enough free space.";

  }


  else if (occupancy < 75) {

    status.textContent =
    "Medium";

    status.className =
    "status medium";

    progress.style.background =
    "#f59e0b";


    document.getElementById("heroStatus")
    .textContent =
    "Medium occupancy";


    document.getElementById("recommendation")
    .textContent =
    "You can take this bus.";


    document.getElementById("recommendationDetail")
    .textContent =
    "The bus may be moderately crowded.";

  }


  else {

    status.textContent =
    "High";

    status.className =
    "status high";

    progress.style.background =
    "#ef4444";


    document.getElementById("heroStatus")
    .textContent =
    "High occupancy";


    document.getElementById("recommendation")
    .textContent =
    "Wait for the next bus if possible.";


    document.getElementById("recommendationDetail")
    .textContent =
    "The next bus may be less crowded.";


    nextBus =
    6;

  }


  progress.style.width =
  occupancy + "%";


  document.getElementById("heroNext")
  .textContent =
  nextBus + " min";


  let context = "";


  if (
    hour >= 7 &&
    hour < 9
  ) {

    context =
    "Morning peak increases expected demand.";

  }


  else if (
    hour >= 17 &&
    hour < 20
  ) {

    context =
    "Evening peak increases expected demand.";

  }


  else {

    context =
    "Normal traffic period.";

  }


  if (stop.hot) {

    context +=
    " This stop is a high-demand location.";

  }


  document.getElementById("contextText")
  .textContent =
  context;

}



function showRouteStops(
  route,
  activeStop
) {

  const container =
  document.getElementById("routeStops");


  container.innerHTML = "";


  route.stops.forEach(
    (stop,index) => {

      const div =
      document.createElement("div");


      div.className =
      "stop";


      if (index === activeStop) {

        div.classList.add(
          "active"
        );

      }


      div.innerHTML =
      `
      <strong>
        ${stop.name}
      </strong>

      ${
        stop.hot
        ?
        '<div class="hotspot">High-demand stop</div>'
        :
        ''
      }
      `;


      container.appendChild(
        div
      );

    }
  );

}



